#!/usr/bin/env python3
"""Generate the BenchVault documentation site from a benchvault checkout.

Everything at the repository root is generated by this script and committed.
Hand-authored sources live in src/. Run:

    python build.py --source ../eln_refactor
"""
from __future__ import annotations

import argparse
import re
import shutil
from pathlib import Path

import markdown

REPO = Path(__file__).resolve().parent
SRC = REPO / "src"

# The five guides the site publishes, in sidebar order.
DOCS: list[tuple[str, str]] = [
    ("INSTALL", "Install Guide"),
    ("USER_GUIDE", "User Guide"),
    ("ADMIN_GUIDE", "Administrator Guide"),
    ("DOCKER_DEPLOY_GUIDE", "Deployment Guide"),
    ("CHANGELOG", "Changelog"),
]

# Legacy v4 URLs that are already indexed and linked. They must redirect,
# not 404.
REDIRECTS: dict[str, str] = {
    "INSTALLATION_GUIDE": "INSTALL.html",
    "LINUX_INSTALLATION_GUIDE": "INSTALL.html",
    "API_SETUP_GUIDE": "DOCKER_DEPLOY_GUIDE.html",
}

_VERSION_RE = re.compile(r'^__version__\s*=\s*["\']([^"\']+)["\']', re.M)

REDIRECT_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta http-equiv="refresh" content="0; url={target}">
<link rel="canonical" href="{target}">
<title>This guide has moved — BenchVault</title>
</head>
<body>
<p>This guide has moved. <a href="{target}">Continue to the current version</a>.</p>
</body>
</html>
"""


def read_version(source: Path) -> str:
    """Read __version__ from the app's utils/version.py.

    Parsed rather than imported: the docs repo must not depend on the
    application being importable, or on its dependencies being installed.
    """
    version_file = Path(source) / "utils" / "version.py"
    match = _VERSION_RE.search(version_file.read_text(encoding="utf-8"))
    if not match:
        raise SystemExit(f"No __version__ assignment found in {version_file}")
    return match.group(1)


def render_markdown(md_text: str) -> str:
    """Convert Markdown to HTML with the extensions the guides rely on.

    `extra` supplies tables and fenced code; `toc` supplies the slugged
    heading ids that cross-document fragment links point at.
    """
    return markdown.Markdown(
        extensions=["extra", "sane_lists", "toc"]
    ).convert(md_text)


def rewrite_doc_links(html: str) -> str:
    """Point intra-document Markdown links at their generated HTML pages.

    Only the five published guides are rewritten. A link to any other .md
    file is left intact so check.py reports it as a broken link rather than
    silently producing a URL that does not exist.
    """
    for slug, _title in DOCS:
        html = html.replace(f'href="{slug}.md"', f'href="{slug}.html"')
        html = html.replace(f'href="{slug}.md#', f'href="{slug}.html#')
    return html


def strip_leading_h1(html: str) -> str:
    """Drop the document's own H1; the layout renders title and version."""
    return re.sub(r"\A\s*<h1[^>]*>.*?</h1>\s*", "", html, count=1, flags=re.S)


def build_nav(current: str) -> str:
    """Sidebar links for the five guides, marking the current page.

    Note the separate `marker` variable: Python 3.11 rejects a backslash
    inside an f-string expression, so the escaped attribute cannot be
    inlined into the f-string.
    """
    items = []
    for slug, title in DOCS:
        marker = ' aria-current="page"' if slug == current else ""
        items.append(f'<a href="{slug}.html"{marker}>{title}</a>')
    return "\n".join(items)


def render_page(layout: str, *, title: str, version: str, nav: str,
                content: str) -> str:
    """Fill the shared doc layout."""
    return (
        layout.replace("{{TITLE}}", title)
        .replace("{{VERSION}}", version)
        .replace("{{NAV}}", nav)
        .replace("{{CONTENT}}", content)
    )


def copy_images(docs_dir: Path) -> int:
    """Rebuild images/ from the app's captures plus the site's brand mark."""
    images = REPO / "images"
    if images.exists():
        shutil.rmtree(images)
    images.mkdir()
    count = 0
    for png in sorted((docs_dir / "images").glob("*.png")):
        shutil.copy2(png, images / png.name)
        count += 1
    shutil.copy2(SRC / "app_icon.png", images / "app_icon.png")
    return count + 1


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source",
        default="../eln_refactor",
        help="Path to the benchvault checkout (default: ../eln_refactor)",
    )
    args = parser.parse_args(argv)

    source = Path(args.source).resolve()
    docs_dir = source / "docs"
    if not docs_dir.is_dir():
        raise SystemExit(f"No docs/ directory under {source} — check --source")

    version = read_version(source)
    layout = (SRC / "layout.html").read_text(encoding="utf-8")

    image_count = copy_images(docs_dir)

    for slug, title in DOCS:
        md_text = (docs_dir / f"{slug}.md").read_text(encoding="utf-8")
        content = strip_leading_h1(rewrite_doc_links(render_markdown(md_text)))
        page = render_page(
            layout, title=title, version=version,
            nav=build_nav(slug), content=content,
        )
        (REPO / f"{slug}.html").write_text(page, encoding="utf-8")

    for slug, target in REDIRECTS.items():
        (REPO / f"{slug}.html").write_text(
            REDIRECT_TEMPLATE.format(target=target), encoding="utf-8"
        )

    landing = (SRC / "index.html").read_text(encoding="utf-8")
    (REPO / "index.html").write_text(
        landing.replace("{{VERSION}}", version), encoding="utf-8"
    )
    shutil.copy2(SRC / "site.css", REPO / "site.css")
    (REPO / ".nojekyll").write_text("", encoding="utf-8")

    print(
        f"Built BenchVault docs site v{version} from {source}: "
        f"{len(DOCS)} guides, {len(REDIRECTS)} redirects, {image_count} images"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
